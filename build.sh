#!/bin/sh
# Build static Wi-Fi overlay APKs for the enable-wifi-7 module.
#
# Requirements (Ubuntu/Debian): apt install aapt apksigner zipalign android-sdk-platform-23 python3 openjdk
#
# Signing key: set KEYSTORE / KS_PASS / KS_ALIAS to use your own key.
# If KEYSTORE is unset, a throwaway key is generated in the output directory.
set -eu

DIR=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-$DIR/out}
ANDROID_JAR=${ANDROID_JAR:-/usr/lib/android-sdk/platforms/android-23/android.jar}
PRIORITY=8003

mkdir -p "$OUT"
if [ -z "${KEYSTORE:-}" ]; then
    KEYSTORE=$OUT/debug.jks KS_PASS=android KS_ALIAS=wifi7
    [ -f "$KEYSTORE" ] || keytool -genkeypair -keystore "$KEYSTORE" -storepass "$KS_PASS" -keypass "$KS_PASS" \
        -alias "$KS_ALIAS" -keyalg RSA -keysize 2048 -validity 36500 -dname "CN=wifi7-overlay" >/dev/null
fi

# build <apk name> <overlay package> <target package>
build() {
    name=$1 pkg=$2 target=$3
    tmp=$(mktemp -d)
    # aapt (API 23 android.jar) can't resolve android:isStatic, so it only builds resources.arsc;
    # the binary manifest is generated by gen_manifest.py.
    cat > "$tmp/AndroidManifest.xml" <<XML
<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="$pkg"/>
XML
    aapt package -f -M "$tmp/AndroidManifest.xml" -S "$DIR/res" -I "$ANDROID_JAR" -F "$tmp/base.apk"
    mkdir "$tmp/stage"
    (cd "$tmp/stage" && unzip -q ../base.apk resources.arsc)
    python3 -I "$DIR/gen_manifest.py" "$tmp/stage/AndroidManifest.xml" "$pkg" "$target" "$PRIORITY"
    (cd "$tmp/stage" && zip -q -X -0 ../unsigned.apk resources.arsc && zip -q -X -9 ../unsigned.apk AndroidManifest.xml)
    zipalign -f -p 4 "$tmp/unsigned.apk" "$tmp/aligned.apk"
    apksigner sign --ks "$KEYSTORE" --ks-pass "pass:$KS_PASS" --ks-key-alias "$KS_ALIAS" --out "$OUT/$name" "$tmp/aligned.apk"
    rm -f "$OUT/$name.idsig"
    rm -rf "$tmp"
    echo "built $OUT/$name"
}

build treble-overlay-wifi7.apk        me.phh.treble.overlay.misc.wifi7        com.android.wifi.resources
build treble-overlay-wifi7-google.apk me.phh.treble.overlay.misc.wifi7.google com.google.android.wifi.resources
